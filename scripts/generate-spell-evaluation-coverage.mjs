import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

import { SPELLS } from '../src/spells.js';

const outputPath = resolve('src', 'ai', 'SPELL_EVALUATION_COVERAGE.md');

const formulaFields = new Set([
  'type',
  'value',
  'base',
  'die',
  'ignoreSpellPower',
  'ignoreArmor',
  'armorMultiplier',
  'addCasterMissingHealthHalf',
  'addCasterMissingHealth',
  'divideByTargetSpeed',
  'roundUp',
  'addCasterArmor',
  'addTargetArmor',
  'addTargetSpeed',
  'addTargetMissingHealth',
  'addResolvedTargetCountMultiplier',
  'maxValue',
  'addTargetEffectNameCount',
  'addTargetEffectCountMultiplier',
  'addTargetEffectsMultiplier',
]);

const fullyEvaluatedPosts = new Set([
  'bypassTriggers',
  'raiseDeadToHeroId',
  'revive',
  'removeCorpse',
  'removeTopDebuff',
  'removeTopPositiveEffect',
  'removeTopEffectByName',
  'onlyApplyIfHasDebuff',
  'onlyApplyToWithEffect',
  'healCasterIfRemoved',
  'secondaryHeal',
  'deltaEnergy',
  'summonFromReserveNearest',
  'placeMineInOpposingColumn',
]);

const markdownCell = (value) => String(value || '—').replaceAll('|', '\\|').replaceAll('\n', '<br>');

const getStatus = (spell) => {
  const spec = spell.spec || {};
  const formula = spec.formula || {};
  const post = spec.post || {};
  const unsupportedFormula = Object.keys(formula).filter(key => !formulaFields.has(key));
  const unsupportedPost = Object.keys(post).filter(key => !fullyEvaluatedPosts.has(key));
  const hasPerTargetExtras = Array.isArray(spec.perTargetExtras) && spec.perTargetExtras.length > 0;
  const effectNeedsSimulation = (spec.effects || []).some(effect => {
    const resolved = typeof effect === 'string' ? null : effect;
    return resolved?.trigger || resolved?.onCastApplyEffectToTargets;
  });

  if (unsupportedFormula.length || unsupportedPost.length || hasPerTargetExtras || effectNeedsSimulation) {
    return 'Partial';
  }
  return 'Covered';
};

const rows = Object.entries(SPELLS)
  .sort(([, left], [, right]) => left.name.localeCompare(right.name))
  .map(([id, spell]) => {
    const spec = spell.spec || {};
    const targetTypes = (spec.targets || []).map(target => target.type || 'projectile').join(', ');
    const formula = spec.formula
      ? Object.entries(spec.formula).map(([key, value]) => `${key}=${value}`).join(', ')
      : '—';
    const post = Object.keys(spec.post || {}).join(', ') || '—';
    const effects = (spec.effects || []).map(effect => typeof effect === 'string' ? effect : effect.name).join(', ') || '—';
    return `| ${markdownCell(spell.name)} | \`${id}\` | ${markdownCell(targetTypes)} | ${markdownCell(formula)} | ${markdownCell(effects)} | ${markdownCell(post)} | ${getStatus(spell)} |`;
  });

const document = `# Spell Evaluation Coverage

Generated by \`npm run ai:coverage\`. Do not edit the per-spell rows manually.

## Evaluation model

EasyAI resolves targets with the same \`resolveTargets\` function used by gameplay. Selector names such as \`highestSpeed\` therefore do not receive an arbitrary score: they resolve to a concrete tile, then the spell score uses that tile's actual health, armor, speed, effects, and position. EasyAIPlus enables its teacher-only advanced evaluation mode for corpses, Raise Dead, Revive, reserve summons, mines, conditional secondary casts, state-aware effect removal, and positional post actions. Standard EasyAI intentionally does not enable those advanced heuristics.

\`Covered\` means every declared formula and post field is handled by the evaluator's generic scoring path. \`Partial\` marks spells that still require a dedicated simulation of an exceptional post action, a per-target sequence, or a triggered/conditional effect.

| Spell | ID | Target selectors | Formula | Effects | Post actions | Coverage |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`;

await writeFile(outputPath, document, 'utf8');
console.log(`Wrote ${outputPath} with ${rows.length} spells.`);
